    # -- GET
    @app.get("/api/chat/load/{chat_id}")
    async def chat_load(chat_id: str, request: fastapi.Request):
        """Loads a specific chat by its id.

        Only the newest `limit` turns are returned, plus the turn_page
        descriptor (start index, total turn count, whether older turns exist)"""
        success = await chat_ops.op_chat_switch(channel, chat_id)
        if not success:
            return utils.api_result("error while loading chat", success=False)

        page, start, total = await _turns_page(channel, None, _page_limit(request))

        chat = dict(channel.context.chat.get())
        chat.update(_page_info(page, start, total))
        chat["token_usage"] = await channel.context.get_total_tokens()
        chat["revision"] = getattr(channel.context.chat.messages, "revision", None)

        await channel.websocket_manager.push_context_update()
        return utils.api_result(chat, success=True)

    @app.get("/api/chat/current")
    async def chat_get_current(request: fastapi.Request):
        """Gives you the currently loaded chat's data, paginated the same way
        /api/chat/load does"""

        page, start, total = await _turns_page(channel, None, _page_limit(request))

        chat = dict(channel.context.chat.get())
        chat.update(_page_info(page, start, total))

        chat["token_usage"] = await channel.context.get_total_tokens()
        chat["revision"] = getattr(channel.context.chat.messages, "revision", None)
        return utils.api_result(chat)

    @app.get("/api/chat/turns")
    async def chat_turns(request: fastapi.Request):
        """One page of the currently loaded chat's turns, oldest first."""
        try:
            before = int(request.query_params.get("before"))
        except (TypeError, ValueError):
            before = None

        page, start, total = await _turns_page(channel, before, _page_limit(request))

        return utils.api_result({
            "turns": page,
            "start": start,
            "total": total,
            "has_more": start > 0
        }, success=True)

    @app.get("/api/stream/state")
    async def stream_state_get():
        """Returns the current stream state as tracked by the backend"""
        return utils.api_result({"state": channel.websocket_manager.stream_state})

    @app.get("/api/chat/export")
    async def chat_export():
        """Gives you the chat history as a human-readable string, plus a safe filename, which you can save to a file or do whatever else with"""
        content = await channel.context.chat.export()
        title = channel.context.chat.get("title") or ""
        safe_title = re.sub(r'[\\/:*?"<>|]', "_", title).strip() or "chat-export"
        return utils.api_result({"content": content, "filename": f"{safe_title}.txt"})

    @app.get("/api/chats")
    async def get_chats(request: fastapi.Request):
        """Returns a list of all chats, with pagination"""
        offset = int(request.query_params.get("offset", 0))
        limit = int(request.query_params.get("limit", 50))
        category = request.query_params.get("category", None)

        all_chats = channel.context.chat.get_all()
        if category:
            all_chats = [c for c in all_chats if c.get("category") == category]

        paginated = all_chats[offset:offset + limit]
        has_more = offset + limit < len(all_chats)

        return utils.api_result({
            "messages": [listing.project_chat(c) for c in paginated],
            "has_more": has_more
        }, success=True)

    # day-grouped chat listing for the sidebar's collapsible date headers
    @app.get("/api/chats/days")
    async def get_chat_days(request: fastapi.Request):
        """Returns the day/last-week/month groups that have chats, newest first, with counts"""
        category = request.query_params.get("category", None)
        tz_offset = int(request.query_params.get("tz_offset", 0))
        
        tags = request.query_params.getlist("tags")

        # sort chats sorted by date descending, grouped by date
        counts = {}
        newest = {}
        for chat in listing.chats_for_category(channel, category, tags):
            updated = chat.get("updated", "")
            key = listing.group_key(updated, tz_offset)
            day = listing.local_day(updated, tz_offset)
            counts[key] = counts.get(key, 0) + 1
            if day > newest.get(key, ""):
                newest[key] = day

        groups = [
            {"key": k, "count": c, "label": listing.day_label_from_key(k, tz_offset)}
            for k, c in counts.items()
        ]
        groups.sort(key=lambda entry: newest.get(entry["key"], ""), reverse=True)

        return utils.api_result(groups, success=True)

    @app.get("/api/chats/day")
    async def get_chats_for_day(request: fastapi.Request):
        """Returns the chats of one day/month group, newest first, paginated"""
        day = request.query_params.get("day", "")
        offset = int(request.query_params.get("offset", 0))
        limit = int(request.query_params.get("limit", 50))
        category = request.query_params.get("category", None)
        tz_offset = int(request.query_params.get("tz_offset", 0))
        tags = request.query_params.getlist("tags")

        day_chats = [
            c for c in listing.chats_for_category(channel, category, tags)
            if listing.group_key(c.get("updated", ""), tz_offset) == day
        ]

        paginated = day_chats[offset:offset + limit]
        has_more = offset + limit < len(day_chats)

        return utils.api_result({
            "messages": [listing.project_chat(c) for c in paginated],
            "has_more": has_more,
            "count": len(day_chats)
        }, success=True)

    @app.get("/api/chats/categories")
    async def get_chat_categories():
        """Returns a list of all existing chat categories, sorted with 'general' pinned to the top"""
        categories = [c or "general" for c in channel.context.chat.get_categories()]
        categories = sorted(set(categories))
        
        # bump it to the TOP! *beat drop*
        if "general" in categories:
            categories.remove("general")
            categories.insert(0, "general")
            
        return utils.api_result(categories, True)

    @app.get("/api/chats/categories/count")
    async def get_chat_category_counts():
        """Returns how many chats are in each category"""
        counts = {}
        for chat in channel.context.chat.data:
            cat = chat.get("category") or "general"
            counts[cat] = counts.get(cat, 0) + 1
            
        return utils.api_result(counts, True)

    @app.get("/api/chats/tags")
    async def get_chat_tags(request: fastapi.Request):
        """Returns the sorted list of tags used by chats"""
        category = request.query_params.get("category", None)

        tags = set()
        for chat in listing.chats_for_category(channel, category):
            for tag in (chat.get("tags") or []):
                if tag:
                    tags.add(tag)

        return utils.api_result(sorted(tags), success=True)

    @app.post("/api/chats/categories/create")
    async def create_chat_category(request: fastapi.Request):
        """Validates a category name and creates a new chat inside it"""
        data = await request.json()
        name = data.get("name") or ""

        error, name = chat_ops.validate_category_name(name, channel.context.chat)
        if error:
            return utils.api_result(error, success=False)

        new_id = await chat_ops.op_chat_new(channel, category=name)
        return utils.api_result({"id": new_id}, True)

    @app.post("/api/chats/categories/delete")
    async def delete_chat_category(request: fastapi.Request):
        """Moves every chat in the given category to 'general', removing the category"""
        data = await request.json()
        name = (data.get("name") or "").strip()

        if not name or name == "general":
            return utils.api_result("'general' cannot be deleted", False)

        chat_store = channel.context.chat

        moved = 0
        for chat in chat_store.data:
            if chat.get("category") == name:
                chat["category"] = "general"
                moved += 1

        if moved:
            chat_store.data.save()

        return utils.api_result({"moved": moved}, True)

    @app.post("/api/chats/search")
    async def search_chats(request: fastapi.Request):
        """Searches across all chats for messages matching a query"""
        data = await request.json()
        query = data.get("query", "").strip()
        search_in_content = data.get("search_in_content", True)
        category = data.get("category")
        # the browser's tz offset (minutes behind UTC), used to bucket
        # results into the same local day groups as the sidebar
        tz_offset = int(data.get("tz_offset") or 0)

        if not query:
            return utils.api_result([])

        results = await channel.context.chat.search(query, search_in_content=search_in_content)

        # filter by category if provided
        if category and category != 'general':
            results = [r for r in results if r.get('category') == category]
        elif category == 'general':
            results = [r for r in results if not r.get('category') or r.get('category') == 'general']

        # respect the sidebar's active tag filter (AND semantics)
        tags = data.get("tags") or []
        if tags:
            results = [r for r in results if all(t in (r.get("tags") or []) for t in tags)]

        # sort by date last modified
        if (data.get("sort") or "updated") != "relevance":
            results.sort(key=lambda r: r.get("updated") or "", reverse=True)

        projected = []
        for chat in results:
            group = listing.group_key(chat.get("updated", ""), tz_offset)
            entry = listing.project_chat(chat, extra_fields=("title_match",))
            entry["group_key"] = group or "undated"
            entry["group_label"] = listing.day_label_from_key(group, tz_offset)
            entry["title_highlighted"] = listing.highlight_query(chat.get("title") or "", query)
            entry["snippets_highlighted"] = [
                listing.highlight_query(snippet, query)
                for snippet in (chat.get("message_snippets") or [])
            ]
            projected.append(entry)

        return utils.api_result(projected)

    @app.get("/api/chat/prompt")
    async def get_prompt():
        try:
            sysprompt = await channel.context.get(system_prompt=True, end_prompt=False, history=False)
        except Exception as e:
            return utils.api_result(str(e), success=False)

        if not sysprompt:
            return utils.api_result("blank context", success=False)

        return utils.api_result(sysprompt[-1].get("content"))

    # -- POST
    @app.post("/api/chat/new")
    async def chat_new(request: fastapi.Request):
        """Creates a new chat.

        Optional json body: category (created inside it), plus title and
        tags - birth metadata for the sidebar's forge flow."""
        category = "general"
        title = ""
        raw_tags = []
        try:
            data = await request.json()
            category = (data.get("category") or "general").strip() or "general"
            title = (data.get("title") or "").strip()
            if isinstance(data.get("tags"), list):
                raw_tags = data.get("tags")
        except Exception:
            pass

        # validate the category it's going to be created in
        if category != "general":
            error, category = chat_ops.validate_category_format(category)
            if error:
                return utils.api_result(error, success=False)

        # normalize tags: drop '#' sigils, empties, dupes; cap count/length
        tags = []
        for tag in raw_tags:
            tag = str(tag).lstrip("#").strip()
            if tag and tag not in tags and len(tags) < 8 and len(tag) <= 32:
                tags.append(tag)

        # clamp the title so a pasted wall of text can't break the sidebar
        title = title[:120]

        new_id = await chat_ops.op_chat_new(
            channel, category=category, title=title or None, tags=tags or None
        )

        await channel.websocket_manager.push_context_update()
        return utils.api_result({"id": new_id})

    @app.post("/api/chat/rename/{chat_id}")
    async def chat_rename(chat_id: str, request: fastapi.Request):
        """Renames a chat by its ID"""
        try:
            data = await request.json()
            new_title = data.get('title', '').strip()
            if not new_title:
                return utils.api_result("Title cannot be empty", success=False)

            renamed = await chat_ops.op_chat_rename(channel, new_title, chat_id=chat_id)
            if not renamed:
                return utils.api_result("Chat not found", success=False)

            return utils.api_result(success=True)
        except Exception as e:
            return utils.api_result(str(e), success=False)

    @app.post("/api/chat/delete/{chat_id}")
    async def chat_delete(chat_id: str):
        """Deletes a chat by its ID"""
        await chat_ops.op_chat_delete(channel, chat_id)
        return utils.api_result(success=True)

    @app.post("/api/chat/set-category/{chat_id}")
    async def chat_set_category(chat_id: str, request: fastapi.Request):
        """Changes the category of a chat by its ID"""
        try:
            data = await request.json()
            category = (data.get('category') or '').strip()
            if not category:
                return utils.api_result("Category cannot be empty", success=False)

            index = channel.context.chat._find_index(chat_id)
            if index is None:
                return utils.api_result("Chat not found", success=False)

            await channel.context.chat.set("category", category, index=index)
            channel.context.chat.data.save()

            return utils.api_result(success=True)
        except Exception as e:
            return utils.api_result(str(e), success=False)

    @app.get("/api/input_history")
    async def input_history_get():
        """Returns the saved input history, oldest first"""
        return utils.api_result(list(channel.input_history), True)

    @app.post("/api/input_history")
    async def input_history_add(request: fastapi.Request):
        """Appends a message to the input history (dedupes against the last entry)"""
        data = await request.json()
        message = (data.get("message") or "").strip()

        if not message:
            return utils.api_result(success=True)

        history = channel.input_history
        history.load()

        if history and history[-1] == message:
            return utils.api_result(list(history), True)

        history.append(message)
        while len(history) > 100:
            history.pop(0)
        history.save()

        return utils.api_result(list(history), True)
